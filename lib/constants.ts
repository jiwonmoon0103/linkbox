// ---------------------------------------------------------------
// 7. 링크 데이터 타입
//    DB의 links 테이블 한 줄과 같은 모양이다.
// ---------------------------------------------------------------

export type Link = {
  id: number
  /** 정규화한 주소 */
  url: string
  title: string
  /** 3줄 요약, 또는 SUMMARY_FAILED / SUMMARY_NONE */
  summary: string
  /** 최대 3개. AI를 부르지 않은 경우 빈 배열 */
  tags: string[]
  /** 저장 시각 (ISO 문자열) */
  created_at: string
}

/** 저장하기 직전의 값. id와 created_at은 DB가 채운다. */
export type NewLink = Omit<Link, 'id' | 'created_at'>

// ---------------------------------------------------------------
// 8. 서버가 주고받는 형식
//    성공은 data, 실패는 error 하나로 고정한다.
// ---------------------------------------------------------------

export type ApiError = {
  error: {
    code: ErrorCode
    message: string
  }
}

/** 저장, 삭제처럼 한 건을 돌려줄 때 */
export type ApiItem<T> = {
  data: T
}

/** 목록, 검색처럼 여러 건을 돌려줄 때 */
export type ApiList<T> = {
  data: T[]
  /** 더 불러올 게 남았는지 */
  hasMore: boolean
}
