// ---------------------------------------------------------------
// 1. 페이지 가져오기
// ---------------------------------------------------------------

/** 페이지를 가져올 때 기다리는 최대 시간. 넘으면 "요약 실패"로 처리한다. */
export const FETCH_TIMEOUT_MS = 15_000

/** AI에 넘기는 본문의 최대 길이. 더 긴 페이지도 앞에서부터 이만큼만 쓴다. */
export const MAX_BODY_CHARS = 5_000

/** 본문이 이보다 짧으면 AI를 호출하지 않고 "요약 없음"으로 저장한다. */
export const MIN_BODY_CHARS = 200

/**
 * 주소가 다른 곳으로 넘길 때 따라가는 최대 횟수.
 * 넘길 때마다 그 주소가 바깥 주소인지 다시 확인하므로, 무한히 따라가지 않게 막는다.
 */
export const MAX_REDIRECTS = 3

/**
 * 페이지 하나에서 받아들이는 최대 크기. (2MB)
 *
 * 15초 제한만으로는 부족하다. 끝없이 쏟아내는 주소를 만나면 15초 동안
 * 받은 것이 전부 메모리에 쌓이고(실측 500MB), 그것을 다시 파싱하다 서버가 죽는다.
 * 본문은 어차피 앞 5,000자만 쓰므로 2MB면 넉넉하다.
 */
export const MAX_RESPONSE_BYTES = 2 * 1024 * 1024

// ---------------------------------------------------------------
// 2. AI 요약과 태그
// ---------------------------------------------------------------

/** 요약에 쓰는 모델. 더 나은 선택지가 생기면 이 줄만 고친다. */
export const AI_MODEL = 'gpt-4o-mini'

/** 요약은 최대 3문장까지만 만든다. */
export const MAX_SUMMARY_SENTENCES = 3

/** 한 문장의 최대 글자 수. 넘으면 잘라내고 말줄임을 붙인다. */
export const MAX_SENTENCE_CHARS = 60

/** 문장이 길 때 뒤에 붙이는 말줄임 표시. */
export const ELLIPSIS = '…'

/** 태그는 최대 3개까지만 저장한다. */
export const MAX_TAGS = 3

/** 태그 하나의 최대 글자 수. 공백은 넣지 않는다. */
export const MAX_TAG_CHARS = 10

/**
 * 제목의 최대 글자 수.
 * 페이지의 title은 남이 만든 값이라 얼마든지 길 수 있다. 제한이 없으면
 * 거대한 title 하나로 AI 요청과 목록 화면을 통째로 부풀릴 수 있다.
 * 카드에서 2줄까지만 보이므로 이보다 길 필요도 없다.
 */
export const MAX_TITLE_CHARS = 200

// ---------------------------------------------------------------
// 3. 목록과 검색
// ---------------------------------------------------------------

/** 한 번에 불러오는 링크 개수. 나머지는 "더 보기"로 가져온다. */
export const PAGE_SIZE = 20

/**
 * 검색어와 태그의 최대 글자 수.
 * 목록 조회는 비밀번호 없이 누구나 부를 수 있다. 상한이 없으면
 * 아주 긴 검색어로 DB에 무거운 질의를 계속 시킬 수 있다.
 */
export const MAX_QUERY_CHARS = 100

/**
 * 건너뛸 수 있는 최대 개수.
 * 설계 기준 규모가 1년 1,200건이라 이 정도면 넉넉하다.
 * 상한이 없으면 offset=999999999 같은 값으로 DB를 헛돌게 할 수 있다.
 */
export const MAX_OFFSET = 10_000

// ---------------------------------------------------------------
// 4. 저장 권한 (비밀번호)
// ---------------------------------------------------------------

/** 비밀번호를 한 번 통과하면 이 시간 동안 다시 묻지 않는다. (1시간) */
export const SESSION_TTL_MS = 60 * 60 * 1_000

/** 이 횟수만큼 연속으로 틀리면 차단한다. */
export const MAX_FAILED_ATTEMPTS = 5

/** 차단이 유지되는 시간. (10분) */
export const BLOCK_DURATION_MS = 10 * 60 * 1_000

/** 통과 여부를 담아 브라우저에 내려보내는 쿠키 이름. */
export const SESSION_COOKIE_NAME = 'linkbox_pass'

// ---------------------------------------------------------------
// 5. 주소 정규화 (중복 저장 판단 기준)
// ---------------------------------------------------------------

/** 주소에서 지워야 하는 추적용 파라미터. utm_로 시작하는 것은 모두 지운다. */
export const TRACKING_PARAM_PREFIXES = ['utm_'] as const
export const TRACKING_PARAMS = ['fbclid', 'gclid', 'ref'] as const

// ---------------------------------------------------------------
